# Ejercicio 14: Tipos de datos (entero, flotante, cadena, caracter, booleano)

# 1. Entero (int)
numero_entero = 10

# 2. Flotante / Decimal (float)
numero_flotante = 3.1416

# 3. Cadena de texto / String (str)
cadena_texto = "Programación en Python"

# 4. Caracter (En Python es una cadena de longitud 1)
caracter = "A"

# 5. Booleano (bool)
booleano = True

# Impresión de los valores y comprobación de su tipo con type()
print(f"Valor: {numero_entero} | Tipo: {type(numero_entero)}")
print(f"Valor: {numero_flotante} | Tipo: {type(numero_flotante)}")
print(f"Valor: '{cadena_texto}' | Tipo: {type(cadena_texto)}")
print(f"Valor: '{caracter}' | Tipo: {type(caracter)}")
print(f"Valor: {booleano} | Tipo: {type(booleano)}")
