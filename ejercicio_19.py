# Ejercicio 19 Promedio de edades
# 1. Declaración de variables con los datos de entrada
edad_branson = 76
edad_bezos = 62
edad_musk = 55

# 2. Proceso: Cálculo del promedio
promedio = (edad_branson + edad_bezos + edad_musk) / 3

# 3. Salida de datos por pantalla
print(f"La edad de Richard Branson es: {edad_branson} años")
print(f"La edad de Jeff Bezos es: {edad_bezos} años")
print(f"La edad de Elon Musk es: {edad_musk} años")
print(f"El promedio de las 3 edades es: {promedio:.2f} años")
